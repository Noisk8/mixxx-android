package org.mixxx;

import android.content.Context;
import android.media.midi.MidiDevice;
import android.media.midi.MidiDeviceInfo;
import android.media.midi.MidiInputPort;
import android.media.midi.MidiManager;
import android.media.midi.MidiOutputPort;
import android.media.midi.MidiReceiver;
import android.os.Bundle;
import android.os.Handler;
import android.os.Looper;
import android.util.Log;

import org.json.JSONArray;
import org.json.JSONException;
import org.json.JSONObject;

import java.io.IOException;
import java.util.Arrays;
import java.util.ArrayList;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.ArrayBlockingQueue;

/**
 * NOTE: This text was autonomously generated by an AI agent.
 *
 * JNI bridge between the native Mixxx MIDI backend (AndroidMidiController)
 * and the android.media.midi framework.
 *
 * One static entry point per operation; native code drives everything:
 * listDevices(), open(), close(), receive(), send(), closeAll().
 *
 * NOTE: This text was autonomously generated by an AI agent.
 */
public final class MidiBridge {
    private static final String TAG = "MixxxMidi";
    private static final int MAX_QUEUED_MESSAGES = 4096;
    private static final long OPEN_TIMEOUT_MS = 5000;

    private static final Handler sMainHandler = new Handler(Looper.getMainLooper());
    private static volatile MidiManager sMidiManager;

    private MidiBridge() {
    }

    private static final class Message {
        final byte[] data;
        final long timestampNanos;

        Message(byte[] data, long timestampNanos) {
            this.data = data;
            this.timestampNanos = timestampNanos;
        }
    }

    private static final class Connection {
        MidiDevice device;
        MidiInputPort inputPort;
        final ArrayList<MidiOutputPort> outputPorts = new ArrayList<>();
        final ArrayList<MidiReceiver> receivers = new ArrayList<>();
        final ArrayBlockingQueue<Message> queue =
                new ArrayBlockingQueue<>(MAX_QUEUED_MESSAGES);
    }

    private static final Map<Integer, Connection> sConnections = new ConcurrentHashMap<>();

    public static void init(Context context) {
        if (context == null) {
            Log.w(TAG, "init called with null context");
            return;
        }
        sMidiManager = (MidiManager) context.getSystemService(Context.MIDI_SERVICE);
        Log.i(TAG, "MidiManager " + (sMidiManager != null ? "ready" : "unavailable"));
    }

    /** Returns a JSON array describing all visible MIDI devices. */
    public static String listDevices() {
        JSONArray array = new JSONArray();
        MidiManager mm = sMidiManager;
        if (mm == null) {
            return array.toString();
        }
        MidiDeviceInfo[] devices = mm.getDevices();
        if (devices == null) {
            return array.toString();
        }
        for (MidiDeviceInfo info : devices) {
            if (info.isPrivate()) {
                continue;
            }
            try {
                JSONObject o = new JSONObject();
                o.put("id", info.getId());
                o.put("type", info.getType());
                Bundle props = info.getProperties();
                o.put("name", props.getString(MidiDeviceInfo.PROPERTY_NAME, ""));
                o.put("manufacturer", props.getString(MidiDeviceInfo.PROPERTY_MANUFACTURER, ""));
                o.put("product", props.getString(MidiDeviceInfo.PROPERTY_PRODUCT, ""));
                o.put("version", props.getString(MidiDeviceInfo.PROPERTY_VERSION, ""));
                o.put("serial", props.getString(MidiDeviceInfo.PROPERTY_SERIAL_NUMBER, ""));
                o.put("inputPorts", info.getInputPortCount());
                o.put("outputPorts", info.getOutputPortCount());
                array.put(o);
            } catch (JSONException e) {
                Log.w(TAG, "unable to serialize device " + info.getId() + ": " + e);
            }
        }
        return array.toString();
    }

    /**
     * NOTE: This text was autonomously generated by an AI agent.
     *
     * Opens the device, its first input port and all available output ports.
     *
     * @param deviceId   MidiDeviceInfo id
     * @param forInput   open a port to send data to the device
     * @param forOutput  open a port to receive data from the device
     * @return true if every requested direction has an available port
     *
     * NOTE: This text was autonomously generated by an AI agent.
     */
    public static boolean open(int deviceId, boolean forInput, boolean forOutput) {
        MidiManager mm = sMidiManager;
        if (mm == null) {
            Log.w(TAG, "open: MidiManager unavailable");
            return false;
        }
        Connection current = sConnections.get(deviceId);
        if (current != null) {
            return (!forInput || current.inputPort != null)
                    && (!forOutput || !current.outputPorts.isEmpty());
        }
        if (Looper.myLooper() == Looper.getMainLooper()) {
            // openDevice() reports via a Handler; blocking here would deadlock.
            Log.e(TAG, "open must not be called on the main thread");
            return false;
        }
        MidiDeviceInfo info = findInfo(mm, deviceId);
        if (info == null) {
            Log.w(TAG, "open: device " + deviceId + " not found");
            return false;
        }

        PendingMidiOpen<MidiDevice> pending = new PendingMidiOpen<>(MidiBridge::closeDevice);
        MidiDevice device;
        try {
            mm.openDevice(info, pending::complete, sMainHandler);
            device = pending.await(OPEN_TIMEOUT_MS);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            return false;
        } catch (RuntimeException e) {
            pending.cancel();
            Log.w(TAG, "open: unable to open device " + deviceId, e);
            return false;
        }
        if (device == null) {
            Log.w(TAG, "open: no device returned before timeout for " + deviceId);
            return false;
        }

        Connection conn = new Connection();
        conn.device = device;
        try {
            if (forOutput) {
                for (int port = 0; port < info.getOutputPortCount(); port++) {
                    MidiOutputPort out = device.openOutputPort(port);
                    if (out == null) {
                        continue;
                    }
                    MidiReceiver receiver = new MidiReceiver() {
                        @Override
                        public void onSend(byte[] data, int offset, int count, long timestamp) {
                            if (count <= 0) {
                                return;
                            }
                            Message message = new Message(
                                    Arrays.copyOfRange(data, offset, offset + count), timestamp);
                            if (!conn.queue.offer(message)) {
                                conn.queue.clear();
                                conn.queue.offer(new Message(new byte[0], 0));
                                conn.queue.offer(message);
                                Log.w(TAG, "MIDI input overflow; parser will resynchronize");
                            }
                        }
                        @Override
                        public void onFlush() {
                            conn.queue.clear();
                            conn.queue.offer(new Message(new byte[0], 0));
                        }
                    };
                    conn.outputPorts.add(out);
                    conn.receivers.add(receiver);
                    out.connect(receiver);
                }
            }
            if (forInput && info.getInputPortCount() > 0) {
                MidiInputPort in = device.openInputPort(0);
                if (in != null) {
                    conn.inputPort = in;
                }
            }

        } catch (RuntimeException e) {
            closeConnection(conn);
            Log.w(TAG, "open: unable to open MIDI ports for " + deviceId, e);
            return false;
        }
        if ((!forInput && !forOutput)
                || (forInput && conn.inputPort == null)
                || (forOutput && conn.outputPorts.isEmpty())) {
            closeConnection(conn);
            Log.w(TAG, "open: required MIDI port unavailable for " + deviceId);
            return false;
        }
        Connection existing = sConnections.putIfAbsent(deviceId, conn);
        if (existing != null) {
            closeConnection(conn);
            return (!forInput || existing.inputPort != null)
                    && (!forOutput || !existing.outputPorts.isEmpty());
        }
        Log.i(TAG, "opened device " + deviceId
                + " inputPort=" + (conn.inputPort != null)
                + " outputPorts=" + conn.outputPorts.size());
        return true;
    }

    /** Closes the device, its ports and discards queued messages. */
    public static void close(int deviceId) {
        Connection conn = sConnections.remove(deviceId);
        if (conn == null) {
            return;
        }
        closeConnection(conn);
        Log.i(TAG, "closed device " + deviceId);
    }

    /** Closes every open connection. Safe to call multiple times. */
    public static void closeAll() {
        for (Integer deviceId : sConnections.keySet().toArray(new Integer[0])) {
            close(deviceId);
        }
    }

    /**
     * Polls one message chunk from the device queue.
     *
     * @param deviceId        the device to poll
     * @param timestampNanos  out parameter receiving the chunk timestamp (ns)
     * @return the raw MIDI bytes or null when the queue is empty
     */
    public static byte[] receive(int deviceId, long[] timestampNanos) {
        Connection conn = sConnections.get(deviceId);
        if (conn == null) {
            return null;
        }
        Message msg = conn.queue.poll();
        if (msg == null) {
            return null;
        }
        if (timestampNanos != null && timestampNanos.length > 0) {
            timestampNanos[0] = msg.timestampNanos;
        }
        return msg.data;
    }

    /** Sends raw MIDI bytes to the device. Returns true on success. */
    public static boolean send(int deviceId, byte[] data) {
        Connection conn = sConnections.get(deviceId);
        if (conn == null || conn.inputPort == null || data == null || data.length == 0) {
            return false;
        }
        try {
            conn.inputPort.send(data, 0, data.length);
            return true;
        } catch (IOException e) {
            Log.w(TAG, "send to device " + deviceId + " failed: " + e);
            return false;
        }
    }

    private static MidiDeviceInfo findInfo(MidiManager mm, int deviceId) {
        MidiDeviceInfo[] devices = mm.getDevices();
        if (devices == null) {
            return null;
        }
        for (MidiDeviceInfo info : devices) {
            if (info.getId() == deviceId) {
                return info;
            }
        }
        return null;
    }

    private static void closeConnection(Connection conn) {
        for (int i = 0; i < conn.outputPorts.size(); i++) {
            try {
                conn.outputPorts.get(i).disconnect(conn.receivers.get(i));
            } catch (Exception e) {
                Log.w(TAG, "disconnect failed: " + e);
            }
        }
        if (conn.inputPort != null) {
            try {
                conn.inputPort.close();
            } catch (IOException e) {
                Log.w(TAG, "closing input port failed: " + e);
            }
        }
        for (MidiOutputPort outputPort : conn.outputPorts) {
            try {
                outputPort.close();
            } catch (IOException e) {
                Log.w(TAG, "closing output port failed: " + e);
            }
        }
        closeDevice(conn.device);
        conn.queue.clear();
    }

    private static void closeDevice(MidiDevice device) {
        if (device != null) {
            try {
                device.close();
            } catch (IOException e) {
                Log.w(TAG, "closing device failed: " + e);
            }
        }
    }
}
