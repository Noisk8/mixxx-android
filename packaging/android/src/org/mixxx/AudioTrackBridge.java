package org.mixxx;

import android.content.Context;
import android.content.Intent;
import android.media.AudioAttributes;
import android.media.AudioDeviceInfo;
import android.media.AudioFormat;
import android.media.AudioManager;
import android.media.AudioTrack;
import android.media.audiofx.AudioEffect;
import android.os.Handler;
import android.os.Looper;
import android.util.Log;
import java.nio.ByteBuffer;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;
import org.json.JSONObject;

public final class AudioTrackBridge {
    private static final String TAG = "MixxxAudioRoutes";
    private static final ConcurrentHashMap<Integer, AudioTrackBridge> OPEN = new ConcurrentHashMap<>();
    private final AudioTrack track;
    private final int deviceId;
    private final int frameBytes;
    private final AudioManager audioManager;
    private final AudioDeviceInfo selectedDevice;
    private final AudioAttributes audioAttributes;
    private final AudioEffect heldEffect;
    private volatile boolean invalidRoute;
    private volatile boolean closed;

    private AudioTrackBridge(AudioTrack track, int deviceId, int channels,
            AudioManager audioManager, AudioDeviceInfo selectedDevice, AudioAttributes audioAttributes,
            AudioEffect heldEffect) {
        this.track = track;
        this.deviceId = deviceId;
        this.audioManager = audioManager;
        this.selectedDevice = selectedDevice;
        this.audioAttributes = audioAttributes;
        this.heldEffect = heldEffect;
        // Autonomously generated by an AI agent.
        // 24-bit packed PCM (3 bytes per sample): 4 channels * 3 = 12 bytes per frame.
        frameBytes = channels * 3;
        // End of comment autonomously generated by an AI agent.
        track.addOnRoutingChangedListener(router -> {
            if (closed) { return; }
            AudioDeviceInfo routed = track.getRoutedDevice();
            if (routed != null && routed.getId() != deviceId) {
                invalidRoute = true;
                try { track.pause(); } catch (IllegalStateException ignored) { }
                Log.e(TAG, "USB output changed unexpectedly: expected=" + deviceId
                        + " actual=" + routed.getId());
                HardwareBridge.outputFailed();
            }
        }, new Handler(Looper.getMainLooper()));
    }

    public static AudioTrackBridge create(Context context, int deviceId,
            int sampleRate, int channels, int frames) {
        AudioTrack track = null;
        AudioAttributes audioAttributes = null;
        AudioManager manager = null;
        AudioDeviceInfo selected = null;
        try {
            manager = (AudioManager) context.getSystemService(Context.AUDIO_SERVICE);
            for (AudioDeviceInfo device : manager.getDevices(AudioManager.GET_DEVICES_OUTPUTS)) {
                if (device.getId() == deviceId) {
                    selected = device;
                    break;
                }
            }
            if (selected == null || channels != 4 || frames <= 0) {
                throw new IllegalArgumentException("Four-channel USB output unavailable");
            }
            // Autonomously generated by an AI agent.
            // A rate mismatch between the requested rate and what the USB
            // endpoint advertises is what makes Android resample the stream and
            // downmix a 4-channel output to a 2-channel mixer (collapsing Master
            // and CUE). Fail loudly instead of silently degrading to stereo.
            int[] deviceRates = selected.getSampleRates();
            boolean rateSupported = false;
            for (int rate : deviceRates) {
                if (rate == sampleRate) { rateSupported = true; break; }
            }
            Log.i(TAG, "USB device id=" + deviceId + " rates="
                    + java.util.Arrays.toString(deviceRates)
                    + " requested=" + sampleRate + " supported=" + rateSupported);
            if (!rateSupported && deviceRates.length > 0) {
                throw new IllegalStateException(
                        "Requested rate " + sampleRate + " not supported by USB endpoint; "
                        + "native rates are " + java.util.Arrays.toString(deviceRates));
            }
            // Autonomously generated by an AI agent.
            // On Android 14+ (API 34+), AudioManager.setPreferredMixerAttributes() allows configuring
            // the hardware USB mixer directly. For multi-channel interfaces like Pioneer DDJ-400,
            // request the 4-channel USB profile at 44100 Hz with index mask 0xf.
            // USAGE_MEDIA is the mandatory usage required by setPreferredMixerAttributes.
            audioAttributes = new AudioAttributes.Builder()
                    .setUsage(AudioAttributes.USAGE_MEDIA)
                    .setContentType(AudioAttributes.CONTENT_TYPE_MUSIC)
                    .build();

            AudioFormat format = new AudioFormat.Builder()
                    .setEncoding(AudioFormat.ENCODING_PCM_24BIT_PACKED)
                    .setSampleRate(sampleRate)
                    .setChannelIndexMask(0xF)
                    .build();

            if (android.os.Build.VERSION.SDK_INT >= android.os.Build.VERSION_CODES.UPSIDE_DOWN_CAKE) {
                try {
                    android.media.AudioMixerAttributes bitPerfectAttr =
                            new android.media.AudioMixerAttributes.Builder(format)
                                    .setMixerBehavior(android.media.AudioMixerAttributes.MIXER_BEHAVIOR_BIT_PERFECT)
                                    .build();
                    boolean prefOk = manager.setPreferredMixerAttributes(audioAttributes, selected, bitPerfectAttr);
                    Log.i(TAG, "setPreferredMixerAttributes BIT_PERFECT: " + prefOk);
                    if (!prefOk) {
                        android.media.AudioMixerAttributes defaultAttr =
                                new android.media.AudioMixerAttributes.Builder(format)
                                        .setMixerBehavior(android.media.AudioMixerAttributes.MIXER_BEHAVIOR_DEFAULT)
                                        .build();
                        boolean defOk = manager.setPreferredMixerAttributes(audioAttributes, selected, defaultAttr);
                        Log.i(TAG, "setPreferredMixerAttributes DEFAULT: " + defOk);
                    }
                } catch (Exception e) {
                    Log.w(TAG, "Error configuring preferred mixer attributes", e);
                }
            }

            try {
                int maxVol = manager.getStreamMaxVolume(AudioManager.STREAM_MUSIC);
                manager.setStreamVolume(AudioManager.STREAM_MUSIC, maxVol, 0);
                Log.i(TAG, "Set USB STREAM_MUSIC volume to max: " + maxVol);
            } catch (Exception e) {
                Log.w(TAG, "Could not set max stream volume", e);
            }

            int frameBytes = channels * 3;
            int minimum = AudioTrack.getMinBufferSize(sampleRate,
                    AudioFormat.CHANNEL_OUT_QUAD, AudioFormat.ENCODING_PCM_24BIT_PACKED);
            if (minimum <= 0) {
                // Some phone audio policies return ERROR_BAD_VALUE for QUAD positional queries.
                // Fall back to stereo * 2 or frames * bytes per frame.
                int stereoMin = AudioTrack.getMinBufferSize(sampleRate,
                        AudioFormat.CHANNEL_OUT_STEREO, AudioFormat.ENCODING_PCM_24BIT_PACKED);
                minimum = (stereoMin > 0) ? stereoMin * 2 : frames * frameBytes * 4;
            }
            int bufferBytes = Math.max(minimum, frames * frameBytes * 3);
            bufferBytes = ((bufferBytes + frameBytes - 1) / frameBytes) * frameBytes;
            track = new AudioTrack.Builder()
                    .setAudioAttributes(audioAttributes)
                    .setAudioFormat(format)
                    .setTransferMode(AudioTrack.MODE_STREAM)
                    .setBufferSizeInBytes(bufferBytes)
                    .setPerformanceMode(AudioTrack.PERFORMANCE_MODE_NONE)
                    .build();
            // End of comment autonomously generated by an AI agent.
            if (track.getState() != AudioTrack.STATE_INITIALIZED
                    || track.getChannelCount() != channels
                    || track.getSampleRate() != sampleRate
                    || track.getFormat().getChannelIndexMask() != 0xF) {
                throw new IllegalStateException("Android rejected independent USB channels");
            }
            if (!track.setPreferredDevice(selected)) {
                throw new IllegalStateException("Android refused the selected USB output");
            }
            Log.i(TAG, "USB preferred device accepted id=" + deviceId);
            AudioEffect heldEffect = disableEffectsOnSession(context, track.getAudioSessionId());
            Log.i(TAG, "AudioTrack USB id=" + deviceId + " channels=" + channels
                    + " indexMask=0xf sampleRate=" + sampleRate
                    + " bufferFrames=" + track.getBufferSizeInFrames()
                    + " session=" + track.getAudioSessionId());
            AudioTrackBridge bridge = new AudioTrackBridge(track, deviceId, channels,
                    manager, selected, audioAttributes, heldEffect);
            OPEN.put(deviceId, bridge);
            return bridge;
        } catch (RuntimeException e) {
            if (track != null) {
                track.release();
            }
            Log.e(TAG, "Cannot open independent USB output", e);
            return null;
        }
    }

    public boolean start() {
        try {
            track.play();
            return true;
        } catch (RuntimeException e) {
            Log.e(TAG, "Cannot start USB output", e);
            return false;
        }
    }

    public int write(ByteBuffer buffer, int offset, int bytes) {
        if (invalidRoute) {
            return AudioTrack.ERROR_DEAD_OBJECT;
        }
        buffer.limit(offset + bytes);
        buffer.position(offset);
        return track.write(buffer, bytes, AudioTrack.WRITE_BLOCKING);
    }

    public void interrupt() {
        invalidRoute = true;
        try { track.pause(); track.flush(); } catch (IllegalStateException ignored) { }
    }

    public int bufferFrames() {
        return track.getBufferSizeInFrames();
    }

    public int playbackHead() { return track.getPlaybackHeadPosition(); }
    public int underrunCount() { return track.getUnderrunCount(); }

    private synchronized void logState() {
        if (closed) { return; }
        AudioDeviceInfo routed = track.getRoutedDevice();
        Log.i(TAG, "USB session=" + track.getAudioSessionId() + " selectedId=" + deviceId
                + " routedId=" + (routed == null ? -1 : routed.getId())
                + " channels=" + track.getChannelCount()
                + " indexMask=" + track.getFormat().getChannelIndexMask()
                + " underruns=" + track.getUnderrunCount()
                + " bufferFrames=" + track.getBufferSizeInFrames());
        try {
            JSONObject sample = new JSONObject();
            sample.put("type", "audio");
            sample.put("selectedId", deviceId);
            sample.put("routedId", routed == null ? -1 : routed.getId());
            sample.put("channels", track.getChannelCount());
            sample.put("indexMask", track.getFormat().getChannelIndexMask());
            sample.put("underruns", track.getUnderrunCount());
            sample.put("bufferFrames", track.getBufferSizeInFrames());
            sample.put("sampleRate", track.getSampleRate());
            SessionDiagnostics.record(sample.toString());
        } catch (Exception e) { Log.w(TAG, "Cannot record USB measurements", e); }
    }

    public static void logAll() {
        for (AudioTrackBridge bridge : OPEN.values()) { bridge.logState(); }
    }

    // Autonomously generated by an AI agent.
    private static AudioEffect disableEffectsOnSession(Context context, int sessionId) {
        try {
            Intent closeIntent = new Intent(AudioEffect.ACTION_CLOSE_AUDIO_EFFECT_CONTROL_SESSION);
            closeIntent.putExtra(AudioEffect.EXTRA_AUDIO_SESSION, sessionId);
            closeIntent.putExtra(AudioEffect.EXTRA_PACKAGE_NAME, context.getPackageName());
            context.sendBroadcast(closeIntent);
        } catch (Exception e) {
            Log.w(TAG, "Cannot broadcast close effect session", e);
        }
        try {
            UUID dolbyUuid = UUID.fromString("40f66c8b-5aa5-4345-8919-53ec431aaa98");
            java.lang.reflect.Constructor<AudioEffect> ctor = AudioEffect.class.getDeclaredConstructor(
                    UUID.class, UUID.class, int.class, int.class);
            ctor.setAccessible(true);
            AudioEffect effect = ctor.newInstance(dolbyUuid, dolbyUuid, 1000, sessionId);
            int status = effect.setEnabled(false);
            Log.i(TAG, "Holding Dolby effect disabled on session " + sessionId
                    + " status=" + status + " enabled=" + effect.getEnabled()
                    + " hasControl=" + effect.hasControl());
            return effect;
        } catch (Exception e) {
            Log.w(TAG, "Could not disable Dolby AudioEffect directly: " + e.getMessage());
            return null;
        }
    }
    // End of comment autonomously generated by an AI agent.

    public synchronized void close() {
        closed = true;
        OPEN.remove(deviceId, this);
        Log.i(TAG, "AudioTrack closed id=" + deviceId + " underruns="
                + track.getUnderrunCount() + " frameBytes=" + frameBytes);
        // Autonomously generated by an AI agent.
        if (android.os.Build.VERSION.SDK_INT >= android.os.Build.VERSION_CODES.UPSIDE_DOWN_CAKE
                && audioManager != null && selectedDevice != null && audioAttributes != null) {
            try {
                audioManager.clearPreferredMixerAttributes(audioAttributes, selectedDevice);
                Log.i(TAG, "Cleared preferred mixer attributes for id=" + deviceId);
            } catch (Exception e) {
                Log.w(TAG, "Failed to clear preferred mixer attributes", e);
            }
        }
        if (heldEffect != null) {
            heldEffect.release();
        }
        // End of comment autonomously generated by an AI agent.
        track.release();
    }
}
